#!/usr/bin/env node

/**
 * Builds the starter site of @chassis-ui/docs the way a Chassis site is built, and checks
 * the output. The package is installed from the output of `pnpm pack`, not from the
 * workspace, so that its `files` and `exports` fields are tested too.
 *
 * Each layout is a repository of its own in a temporary directory:
 *
 * - `root`: the site is in `site/` and is built from the root of the repository with
 *   `astro build --root site`, like chassis-assets, chassis-icons and chassis-figma.
 * - `packages`: the site is the workspace package `packages/site` and is built with
 *   `pnpm --filter`, like chassis-tokens, chassis-css and chassis-react. It is type-checked
 *   as well.
 *
 * In both, the code that the site documents sits outside the site, and `sourceDir` points
 * to it.
 *
 * Usage: node build/fixture-sites.js [root|packages ...] [--keep]
 */

import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const packageDir = path.join(repositoryRoot, 'packages/docs')
const starterDir = path.join(packageDir, 'starter')
const assetsDir = path.join(repositoryRoot, 'vendor/assets')

// Generated by the starter or by a local run of it. Not part of the starter.
const ignoredPaths = new Set(['node_modules', 'dist', '.astro', path.join('public', 'static')])

// Import paths that the package README documents, and paths that 0.6.0 stopped resolving.
const supportedImports = [
  '@chassis-ui/docs',
  '@chassis-ui/docs/integration',
  '@chassis-ui/docs/schema',
  '@chassis-ui/docs/site',
  '@chassis-ui/docs/layouts/DocsLayout.astro',
  '@chassis-ui/docs/components/FeatureCard.astro',
  '@chassis-ui/docs/shortcodes/Code.astro',
  '@chassis-ui/docs/js/example-mode.js',
  '@chassis-ui/docs/scss/main',
  '@chassis-ui/docs/scss/vars'
]
const removedImports = [
  '@chassis-ui/docs/components/shortcodes/Icon.astro',
  '@chassis-ui/docs/layouts/head/Head.astro',
  '@chassis-ui/docs/libs/utils.ts',
  '@chassis-ui/docs/scss/_search.scss',
  '@chassis-ui/docs/src/js/color-modes.js'
]

const layouts = {
  root: {
    sitePath: 'site',
    sourcePath: 'source',
    sourceDir: '../source',
    build: ['exec', 'astro', 'build', '--root', 'site'],
    check: false
  },
  packages: {
    sitePath: 'packages/site',
    sourcePath: 'packages/source',
    sourceDir: '../source',
    build: ['--filter', 'chassis-docs-starter', 'build'],
    check: ['--filter', 'chassis-docs-starter', 'check']
  }
}

function run(command, args, cwd) {
  console.log(`\n$ ${[command, ...args].join(' ')}  (in ${cwd})`)
  execFileSync(command, args, { cwd, stdio: 'inherit' })
}

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'))
}

function writeJson(file, data) {
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`)
}

// Replaces the value of a top-level key of `config.yml`, keeping the rest of the file.
function setConfigKey(file, key, value) {
  const text = fs.readFileSync(file, 'utf8')
  const pattern = new RegExp(`^${key}:.*$`, 'm')

  assert.match(text, pattern, `${key} is missing from ${file}`)
  fs.writeFileSync(file, text.replace(pattern, `${key}: '${value}'`))
}

function pack(tempDir) {
  run('pnpm', ['pack', '--pack-destination', tempDir], packageDir)

  const tarball = fs.readdirSync(tempDir).find((file) => file.endsWith('.tgz'))

  assert.ok(tarball, 'pnpm pack wrote no tarball')

  return path.join(tempDir, tarball)
}

function createRepository(name, layout, tarball, tempDir) {
  const repositoryDir = path.join(tempDir, name)
  const siteDir = path.join(repositoryDir, layout.sitePath)
  const sourceDir = path.join(repositoryDir, layout.sourcePath)

  fs.cpSync(starterDir, siteDir, {
    recursive: true,
    filter: (source) => !ignoredPaths.has(path.relative(starterDir, source))
  })

  // The code that the site documents moves out of the site.
  fs.renameSync(path.join(siteDir, 'source'), sourceDir)

  const configFile = path.join(siteDir, 'config.yml')

  setConfigKey(configFile, 'sourceDir', layout.sourceDir)
  setConfigKey(configFile, 'sourcePath', layout.sourcePath)
  setConfigKey(configFile, 'sitePath', layout.sitePath)

  const manifest = readJson(path.join(siteDir, 'package.json'))

  manifest.dependencies['@chassis-ui/docs'] = `file:${tarball}`

  if (name === 'root') {
    // One manifest, at the root of the repository.
    fs.rmSync(path.join(siteDir, 'package.json'))
    writeJson(path.join(repositoryDir, 'package.json'), manifest)
  } else {
    writeJson(path.join(siteDir, 'package.json'), manifest)
    writeJson(path.join(repositoryDir, 'package.json'), { name: 'fixture', private: true })
    fs.writeFileSync(
      path.join(repositoryDir, 'pnpm-workspace.yaml'),
      "packages:\n  - 'packages/*'\n"
    )
  }

  // Every Chassis site has the docs build of chassis-assets as the `vendor/assets` submodule.
  assert.ok(
    fs.existsSync(path.join(assetsDir, 'dist')),
    `${assetsDir} is empty. Run: git submodule update --init vendor/assets`
  )
  fs.mkdirSync(path.join(repositoryDir, 'vendor'))
  fs.symlinkSync(assetsDir, path.join(repositoryDir, 'vendor/assets'), 'dir')

  run('git', ['init', '--quiet'], repositoryDir)

  return { repositoryDir, siteDir }
}

function readBuiltFile(distDir, file) {
  const builtFile = path.join(distDir, file)

  assert.ok(fs.existsSync(builtFile), `${file} was not built`)

  return fs.readFileSync(builtFile, 'utf8')
}

// Resolves each import path from the site, the way Node and Vite read `exports`.
function checkExports(siteDir) {
  const script = `
    const resolves = (specifier) => {
      try {
        import.meta.resolve(specifier)
        return true
      } catch {
        return false
      }
    }
    console.log(JSON.stringify({
      unresolved: ${JSON.stringify(supportedImports)}.filter((s) => !resolves(s)),
      resolved: ${JSON.stringify(removedImports)}.filter(resolves)
    }))
  `
  const output = execFileSync(process.execPath, ['--input-type=module', '-e', script], {
    cwd: siteDir,
    encoding: 'utf8'
  })
  const { unresolved, resolved } = JSON.parse(output)

  assert.deepEqual(unresolved, [], 'Documented import paths do not resolve')
  assert.deepEqual(resolved, [], 'Import paths that are not public still resolve')
}

function checkOutput(layout, siteDir) {
  const distDir = path.join(siteDir, 'dist')
  const repo = 'https://github.com/chassis-ui/website'
  const page = readBuiltFile(distDir, 'docs/getting-started/shortcodes/index.html')

  // The file components read from `sourceDir`, not from the working directory.
  assert.match(page, /toggleExample/, '<JsDocs> and <Code filePath> did not render js/example.js')
  assert.match(page, /example-gap-/, '<ScssDocs> did not render scss/_example.scss')
  assert.ok(
    page.includes(`${repo}/blob/v0.1.0/${layout.sourcePath}/js/example.js`),
    'The link to the source file is wrong'
  )

  // "View on GitHub" links to the page's own file.
  assert.ok(
    page.includes(
      `${repo}/blob/main/${layout.sitePath}/content/docs/getting-started/shortcodes.mdx`
    ),
    '"View on GitHub" links to the wrong file'
  )

  // Named callouts, redirects and the static files.
  assert.match(
    readBuiltFile(distDir, 'docs/getting-started/introduction/index.html'),
    /A named callout\./,
    '<Callout name> did not render'
  )
  assert.match(readBuiltFile(distDir, 'shortcodes/index.html'), /http-equiv="refresh"/)
  assert.match(readBuiltFile(distDir, 'docs/shortcodes/index.html'), /http-equiv="refresh"/)
  readBuiltFile(distDir, 'static/images/site-logo.svg')
  readBuiltFile(distDir, 'static/css/chassis.min.css')
  readBuiltFile(distDir, 'static/icons/chassis-icons.css')

  // `src/scss/docs.scss` of the starter, which uses `scss/vars` and `scss/main`, compiled.
  const stylesheets = fs
    .readdirSync(distDir, { recursive: true })
    .filter((file) => file.endsWith('.css') && !file.startsWith('static'))
    .map((file) => fs.readFileSync(path.join(distDir, file), 'utf8'))

  assert.ok(
    stylesheets.some((css) => css.includes('.example-gap-md')),
    'The stylesheet of the site is missing from the build'
  )
}

const args = process.argv.slice(2)
const keep = args.includes('--keep')
const names = args.filter((arg) => !arg.startsWith('--'))
const selected = names.length > 0 ? names : Object.keys(layouts)

for (const name of selected) {
  assert.ok(
    name in layouts,
    `Unknown layout '${name}'. Expected: ${Object.keys(layouts).join(', ')}`
  )
}

const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'chassis-docs-fixtures-'))

try {
  const tarball = pack(tempDir)

  for (const name of selected) {
    const layout = layouts[name]
    const { repositoryDir, siteDir } = createRepository(name, layout, tarball, tempDir)

    run('pnpm', ['install'], repositoryDir)
    checkExports(siteDir)

    if (layout.check) {
      run('pnpm', layout.check, repositoryDir)
    }

    run('pnpm', layout.build, repositoryDir)
    checkOutput(layout, siteDir)
    console.log(`\nThe '${name}' layout built and passed its checks.`)
  }
} finally {
  if (keep) {
    console.log(`\nKept ${tempDir}`)
  } else {
    fs.rmSync(tempDir, { force: true, recursive: true })
  }
}
